import { useEffect, useRef, useState } from "react";
import { createPortal } from "react-dom";
import {
  Camera,
  ExternalLink,
  Globe,
  ImageOff,
  Loader2,
  Monitor,
  RefreshCw,
  ShieldQuestion,
  Smartphone,
  Tablet,
  X,
} from "lucide-react";

import Button from "../ui/Button";
import { Github } from "../brand/BrandIcons";
import useFocusTrap from "../../hooks/useFocusTrap";
import { cn, hostFromUrl, safeText } from "../../lib/utils";

/** How long a frame may stay blank before we suggest the screenshot preview. */
const SLOW_LOAD_MS = 7000;

/**
 * A static screenshot of a live URL, generated by WordPress's public mShots
 * service. This is the fallback that makes previews work for the many sites
 * that refuse to be framed (`X-Frame-Options` / CSP `frame-ancestors`):
 * browsers give us no reliable signal that a frame was blocked — the error
 * page still fires `load` — so instead of staring at a blank white box the
 * viewer can always fall back to (or auto-switch to) this image.
 */
export function screenshotUrl(url, width = 1280) {
  if (!url) return "";
  try {
    const parsed = new URL(url);
    if (!["http:", "https:"].includes(parsed.protocol)) return "";
    return `https://s0.wp.com/mshots/v1/${encodeURIComponent(parsed.href)}?w=${width}`;
  } catch {
    return "";
  }
}

const DEVICES = [
  { id: "desktop", label: "Desktop", icon: Monitor, width: "100%" },
  { id: "tablet", label: "Tablet", icon: Tablet, width: "768px" },
  { id: "mobile", label: "Mobile", icon: Smartphone, width: "390px" },
];

/**
 * Embedded pages are untrusted third-party code, so they run inside a sandbox
 * and can never navigate or restyle the hub. `allow-same-origin` is dropped
 * when the target is this very origin: a same-origin frame with both
 * `allow-scripts` and `allow-same-origin` could reach out of the sandbox.
 */
function sandboxFor(url) {
  const base = [
    "allow-scripts",
    "allow-forms",
    "allow-popups",
    "allow-popups-to-escape-sandbox",
    "allow-modals",
    "allow-downloads",
  ];
  try {
    const sameOrigin = new URL(url, window.location.origin).origin === window.location.origin;
    return sameOrigin ? base.join(" ") : ["allow-same-origin", ...base].join(" ");
  } catch {
    return base.join(" ");
  }
}

/**
 * The "project window": every project's live URL previews inside the hub.
 *
 * Preview strategy (why it no longer shows a blank white box):
 *  1. Try the live site in a sandboxed iframe, with desktop / tablet /
 *     mobile viewport widths so responsive demos can be checked.
 *  2. If the frame is still loading after {@link SLOW_LOAD_MS} — the usual
 *     signature of a site blocking framing — automatically switch to the
 *     screenshot preview and say why.
 *  3. A slim hint bar under a loaded frame offers the screenshot and the
 *     open-in-a-tab escape hatch at all times, and the screenshot itself
 *     degrades to a friendly panel if it cannot be generated.
 */
export default function ProjectViewer({ project, open, onClose }) {
  const panelRef = useRef(null);
  const [state, setState] = useState("loading"); // loading | ready | slow
  const [view, setView] = useState("live"); // live | screenshot
  const [device, setDevice] = useState("desktop");
  const [nonce, setNonce] = useState(0);
  const [hintDismissed, setHintDismissed] = useState(false);
  const [shotBroken, setShotBroken] = useState(false);
  const slowTimer = useRef(null);

  const url = project?.live_url || "";
  const title = safeText(project?.title, "Project");
  const host = hostFromUrl(url);
  const sandbox = open && url ? sandboxFor(url) : "";
  const shot = screenshotUrl(url);
  const deviceWidth = DEVICES.find((item) => item.id === device)?.width || "100%";

  useFocusTrap(panelRef, Boolean(open), {
    onEscape: onClose,
    initialFocus: "[data-autofocus]",
  });

  // Fresh state every time the window is opened, reloaded or retargeted.
  useEffect(() => {
    if (!open) return undefined;
    setState("loading");
    setView("live");
    setHintDismissed(false);
    setShotBroken(false);
    clearTimeout(slowTimer.current);
    slowTimer.current = setTimeout(() => {
      // Still blank after the budget: most likely framed-blocked. Fall back
      // to the screenshot instead of leaving a white void on screen.
      setState((current) => (current === "loading" ? "slow" : current));
      setView((current) => (current === "live" ? "screenshot" : current));
    }, SLOW_LOAD_MS);
    return () => clearTimeout(slowTimer.current);
  }, [open, nonce, url]);

  // Keep the page behind the window still.
  useEffect(() => {
    if (!open || typeof document === "undefined") return undefined;
    const previous = document.body.style.overflow;
    document.body.style.overflow = "hidden";
    return () => {
      document.body.style.overflow = previous;
    };
  }, [open]);

  if (!open) return null;

  const reload = () => setNonce((value) => value + 1);

  return createPortal(
    <div className="fixed inset-0 z-[94] flex items-end justify-center p-0 sm:items-center sm:p-5">
      <div
        className="absolute inset-0 bg-slate-950/80 backdrop-blur-sm"
        onClick={onClose}
        aria-hidden="true"
      />
      <div
        ref={panelRef}
        role="dialog"
        aria-modal="true"
        aria-labelledby="project-viewer-title"
        className="relative flex h-[100dvh] w-full max-w-6xl animate-rise flex-col overflow-hidden rounded-t-3xl border border-line-strong bg-surface-solid shadow-2xl sm:h-[92dvh] sm:rounded-3xl"
      >
        {/* Title bar */}
        <div className="flex flex-wrap items-center gap-3 border-b border-line px-4 py-3 sm:px-5">
          <span className="flex gap-1.5" aria-hidden="true">
            <span className="h-2.5 w-2.5 rounded-full bg-rose-400/80" />
            <span className="h-2.5 w-2.5 rounded-full bg-amber-400/80" />
            <span className="h-2.5 w-2.5 rounded-full bg-emerald-400/80" />
          </span>

          <div className="min-w-0 flex-1">
            <h2 id="project-viewer-title" className="truncate text-sm font-bold text-ink">
              {title}
            </h2>
            <p className="flex items-center gap-1.5 truncate text-xs text-muted">
              <Globe className="h-3 w-3 shrink-0" aria-hidden="true" />
              {host || "No live URL"}
              <span className="hidden sm:inline">
                · {view === "live" ? "running in a sandboxed window" : "screenshot preview"}
              </span>
            </p>
          </div>

          <div className="flex items-center gap-1.5">
            <Button
              variant="ghost"
              size="icon"
              onClick={reload}
              disabled={!url}
              aria-label="Reload project"
              title="Reload"
            >
              <RefreshCw className="h-4 w-4" aria-hidden="true" />
            </Button>
            {url ? (
              <Button
                variant="ghost"
                size="icon"
                href={url}
                aria-label="Open project in a new tab"
                title="Open in a new tab"
                data-autofocus
              >
                <ExternalLink className="h-4 w-4" aria-hidden="true" />
              </Button>
            ) : null}
            <Button
              variant="ghost"
              size="icon"
              onClick={onClose}
              aria-label="Close project window"
              title="Close"
            >
              <X className="h-4 w-4" aria-hidden="true" />
            </Button>
          </div>
        </div>

        {/* Preview toolbar: viewport width + live/screenshot switch */}
        {url ? (
          <div className="flex flex-wrap items-center gap-2 border-b border-line bg-surface px-4 py-2 sm:px-5">
            <div
              className="flex rounded-lg border border-line-strong p-0.5"
              role="group"
              aria-label="Preview device width"
            >
              {DEVICES.map((item) => {
                const Icon = item.icon;
                const active = device === item.id;
                return (
                  <button
                    key={item.id}
                    type="button"
                    onClick={() => setDevice(item.id)}
                    aria-pressed={active}
                    title={`${item.label} preview`}
                    className={cn(
                      "flex items-center gap-1.5 rounded-md px-2.5 py-1.5 text-[0.7rem] font-semibold transition",
                      active ? "bg-brand-500/25 text-ink" : "text-muted hover:text-ink"
                    )}
                  >
                    <Icon className="h-3.5 w-3.5" aria-hidden="true" />
                    <span className="hidden sm:inline">{item.label}</span>
                  </button>
                );
              })}
            </div>

            <div
              className="ml-auto flex rounded-lg border border-line-strong p-0.5"
              role="group"
              aria-label="Preview mode"
            >
              <button
                type="button"
                onClick={() => setView("live")}
                aria-pressed={view === "live"}
                className={cn(
                  "flex items-center gap-1.5 rounded-md px-2.5 py-1.5 text-[0.7rem] font-semibold transition",
                  view === "live" ? "bg-brand-500/25 text-ink" : "text-muted hover:text-ink"
                )}
              >
                <Globe className="h-3.5 w-3.5" aria-hidden="true" />
                Live iframe
              </button>
              <button
                type="button"
                onClick={() => setView("screenshot")}
                aria-pressed={view === "screenshot"}
                className={cn(
                  "flex items-center gap-1.5 rounded-md px-2.5 py-1.5 text-[0.7rem] font-semibold transition",
                  view === "screenshot" ? "bg-brand-500/25 text-ink" : "text-muted hover:text-ink"
                )}
              >
                <Camera className="h-3.5 w-3.5" aria-hidden="true" />
                Screenshot
              </button>
            </div>
          </div>
        ) : null}

        {/* Frame / screenshot */}
        <div className="relative flex flex-1 justify-center overflow-auto bg-slate-950/40">
          {url ? (
            <>
              {view === "live" ? (
                <div
                  className="h-full shrink-0 transition-[width] duration-300 ease-out"
                  style={{ width: deviceWidth, maxWidth: "100%" }}
                >
                  <iframe
                    key={nonce}
                    src={url}
                    title={`${title} — live project`}
                    className="h-full w-full border-0 bg-white"
                    sandbox={sandbox}
                    referrerPolicy="no-referrer"
                    allow="fullscreen; clipboard-write"
                    allowFullScreen
                    onLoad={() => setState((current) => (current === "loading" ? "ready" : current))}
                  />
                </div>
              ) : shot && !shotBroken ? (
                <div
                  className="shrink-0 self-start transition-[width] duration-300 ease-out"
                  style={{ width: deviceWidth, maxWidth: "100%" }}
                >
                  <img
                    key={`${nonce}-shot`}
                    src={shot}
                    alt={`Screenshot preview of ${title} (${host})`}
                    className="w-full bg-white"
                    loading="lazy"
                    decoding="async"
                    onLoad={() => setState((current) => (current === "loading" ? "ready" : current))}
                    onError={() => setShotBroken(true)}
                  />
                </div>
              ) : (
                <div className="flex h-full w-full flex-col items-center justify-center gap-4 p-8 text-center">
                  <span className="grid h-14 w-14 place-items-center rounded-2xl border border-line-strong bg-brand-500/10 text-brand-300">
                    <ImageOff className="h-6 w-6" aria-hidden="true" />
                  </span>
                  <div>
                    <h3 className="text-base font-bold text-ink">No preview available for this site</h3>
                    <p className="mx-auto mt-1 max-w-md text-sm leading-relaxed text-muted">
                      {host || "This site"} blocks embedding and no screenshot could be generated. Open it in
                      a real tab instead — it will work there.
                    </p>
                  </div>
                  <div className="flex flex-wrap justify-center gap-2">
                    <Button size="sm" href={url} iconRight={ExternalLink}>
                      Open in a tab
                    </Button>
                    {project?.repo_url ? (
                      <Button size="sm" variant="ghost" href={project.repo_url} icon={Github}>
                        Open repository
                      </Button>
                    ) : null}
                  </div>
                </div>
              )}

              {state === "loading" ? (
                <div className="pointer-events-none absolute inset-0 flex flex-col items-center justify-center gap-3 bg-surface-solid">
                  <Loader2 className="h-6 w-6 animate-spin text-brand-300" aria-hidden="true" />
                  <p className="text-sm font-semibold text-muted">
                    {view === "live" ? `Loading ${host || "project"}…` : "Generating screenshot…"}
                  </p>
                </div>
              ) : null}

              {state === "slow" ? (
                <div className="absolute inset-x-0 bottom-0 flex flex-wrap items-center justify-between gap-3 border-t border-amber-400/30 bg-surface-solid/95 px-4 py-3 text-xs text-muted backdrop-blur">
                  <span className="flex items-start gap-2">
                    <ShieldQuestion className="mt-0.5 h-4 w-4 shrink-0 text-amber-300" aria-hidden="true" />
                    This site looks like it blocks embedding (X-Frame-Options / CSP) — showing the screenshot
                    preview instead.
                  </span>
                  <span className="flex gap-2">
                    <Button
                      variant="ghost"
                      size="sm"
                      onClick={() => {
                        setView("live");
                        reload();
                      }}
                    >
                      Retry live
                    </Button>
                    <Button variant="ghost" size="sm" href={url} iconRight={ExternalLink}>
                      Open in a tab
                    </Button>
                  </span>
                </div>
              ) : state === "ready" && view === "live" && !hintDismissed ? (
                <div className="absolute inset-x-0 bottom-0 flex flex-wrap items-center justify-between gap-3 border-t border-line bg-surface-solid/90 px-4 py-2.5 text-xs text-muted backdrop-blur">
                  <span className="flex items-center gap-2">
                    <ShieldQuestion className="h-4 w-4 shrink-0 text-muted" aria-hidden="true" />
                    Blank or broken inside the frame? The site may block embedding.
                  </span>
                  <span className="flex items-center gap-2">
                    <Button variant="ghost" size="sm" onClick={() => setView("screenshot")} icon={Camera}>
                      Screenshot
                    </Button>
                    <Button variant="ghost" size="sm" href={url} iconRight={ExternalLink}>
                      Open in a tab
                    </Button>
                    <button
                      type="button"
                      onClick={() => setHintDismissed(true)}
                      className="rounded-md p-1 text-muted transition hover:text-ink"
                      aria-label="Dismiss preview hint"
                    >
                      <X className="h-3.5 w-3.5" aria-hidden="true" />
                    </button>
                  </span>
                </div>
              ) : null}
            </>
          ) : (
            <div className="flex h-full w-full flex-col items-center justify-center gap-4 p-8 text-center">
              <span className="grid h-14 w-14 place-items-center rounded-2xl border border-line-strong bg-brand-500/10 text-brand-300">
                <Globe className="h-6 w-6" aria-hidden="true" />
              </span>
              <div>
                <h3 className="text-base font-bold text-ink">No live URL yet</h3>
                <p className="mx-auto mt-1 max-w-md text-sm leading-relaxed text-muted">
                  This project has not published a demo. Ask the author for a live link, or browse the source
                  instead.
                </p>
              </div>
              {project?.repo_url ? (
                <Button variant="ghost" href={project.repo_url} icon={Github}>
                  Open repository
                </Button>
              ) : null}
            </div>
          )}
        </div>
      </div>
    </div>,
    document.body
  );
}

/** Re-exported for the cards that need to know whether a project can be framed. */
export function canEmbed(project) {
  if (!project?.live_url) return false;
  try {
    const url = new URL(project.live_url, window.location.origin);
    return ["http:", "https:"].includes(url.protocol);
  } catch {
    return false;
  }
}
